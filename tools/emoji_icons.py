#!/usr/bin/env python3
"""Turn emoji into RGB565 pictures for the CYD (TFT_eSPI pushImage), written as a C header.

Uses the Noto Color Emoji font (SIL Open Font License). Transparent pixels become ICON_KEY (magenta),
so draw them with tft.pushImage(x, y, w, h, data, ICON_KEY).

  python3 tools/emoji_icons.py > firmware/cyd/cyd_menu/icons.h
"""
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/noto/NotoColorEmoji.ttf"
KEY = 0xF81F  # magenta = see-through

ICONS = [  # (C name, emoji, size)
    ("LION", "🦁", 48), ("EAGLE", "🦅", 48), ("BADGER", "🦡", 48), ("SNAKE", "🐍", 48),
    ("HAT", "🎩", 48), ("OWL", "🦉", 48), ("LETTER", "💌", 48), ("TROPHY", "🏆", 48),
    ("BULB", "💡", 48), ("STAR", "⭐", 48), ("FEATHER", "🪶", 48), ("ZAP", "⚡", 48), ("BOOM", "💥", 48),
    ("WAND", "🪄", 48), ("POTION", "🧪", 48), ("BOOK", "📖", 32),
    ("CAMERA", "📷", 48), ("DANCER", "💃", 48), ("DISCO", "🪩", 48),
    # potion ingredients, same order as the web page
    ("I_UNICORN", "🦄", 32), ("I_FROG", "🐸", 32), ("I_RAINBOW", "🌈", 32), ("I_SPIDER", "🕷️", 32),
    ("I_CANDY", "🍬", 32), ("I_PEPPER", "🌶️", 32), ("I_FEATHER", "🪶", 32), ("I_STAR", "⭐", 32),
]

font = ImageFont.truetype(FONT, 109)  # the only size this bitmap font has


def render(ch, size):
    im = Image.new("RGBA", (136, 128), (0, 0, 0, 0))
    ImageDraw.Draw(im).text((0, 0), ch, font=font, embedded_color=True)
    im = im.crop(im.getbbox()).resize((size, size), Image.LANCZOS)
    out = []
    for r, g, b, a in im.getdata():
        if a < 128:
            out.append(KEY)
        else:
            v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
            out.append(v ^ 0x0020 if v == KEY else v)  # never accidentally see-through
    return out


print("// Generated by tools/emoji_icons.py from Noto Color Emoji (SIL Open Font License). Don't edit by hand.")
print("#pragma once")
print(f"#define ICON_KEY 0x{KEY:04X}")
for name, ch, size in ICONS:
    px = render(ch, size)
    print(f"#define {name}_W {size}")
    print(f"const uint16_t {name}[] PROGMEM = {{")
    for i in range(0, len(px), 16):
        print("  " + ", ".join(f"0x{v:04X}" for v in px[i:i + 16]) + ",")
    print("};")
print("const uint16_t* const INGREDIENT_ICONS[8] = {I_UNICORN, I_FROG, I_RAINBOW, I_SPIDER, I_CANDY, I_PEPPER, I_FEATHER, I_STAR};")
print("const uint16_t* const HOUSE_ICONS[4] = {LION, EAGLE, BADGER, SNAKE};")
